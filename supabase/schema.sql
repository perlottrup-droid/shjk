-- Sidequest shared social data. Apply once in the Supabase SQL Editor.
create table if not exists public.profiles (
  telegram_id text primary key,
  name text not null,
  username text not null default '',
  photo_url text not null default '',
  created_at timestamptz not null default now()
);

create table if not exists public.posts (
  id bigint generated by default as identity primary key,
  user_id text not null references public.profiles(telegram_id) on delete cascade,
  text varchar(500) not null,
  created_at timestamptz not null default now()
);

create table if not exists public.likes (
  post_id bigint not null references public.posts(id) on delete cascade,
  user_id text not null references public.profiles(telegram_id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (post_id, user_id)
);

create table if not exists public.comments (
  id bigint generated by default as identity primary key,
  post_id bigint not null references public.posts(id) on delete cascade,
  user_id text not null references public.profiles(telegram_id) on delete cascade,
  text varchar(180) not null,
  created_at timestamptz not null default now()
);

create table if not exists public.follows (
  follower_id text not null references public.profiles(telegram_id) on delete cascade,
  followed_id text not null references public.profiles(telegram_id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (follower_id, followed_id),
  check (follower_id <> followed_id)
);

create index if not exists posts_created_at_idx on public.posts (created_at desc);
create index if not exists comments_post_id_idx on public.comments (post_id, created_at);
create index if not exists follows_follower_idx on public.follows (follower_id);

alter table public.profiles enable row level security;
alter table public.posts enable row level security;
alter table public.likes enable row level security;
alter table public.comments enable row level security;
alter table public.follows enable row level security;

